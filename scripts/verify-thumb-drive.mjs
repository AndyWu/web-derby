import { chromium, webkit } from '@playwright/test';
import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
await mkdir('verification/thumb-drive', { recursive:true });
const hardStop=setTimeout(()=>process.exit(2),120000);
const results=[];
for (const [name, engine] of [['chromium',chromium],['webkit',webkit]]) {
  const browser=await engine.launch({ headless:true, ...(name==='chromium'?{args:['--enable-unsafe-swiftshader']}:{}) });
  try {
    const page=await browser.newPage({viewport:{width:844,height:390},isMobile:true,hasTouch:true});
    const errors=[];
    page.on('pageerror',e=>errors.push(e.message));
    await page.addInitScript(()=>localStorage.setItem('derby-controls-seen','1'));
    page.setDefaultTimeout(20000);
    console.log(name, 'loading');
    await page.goto('http://localhost:5173');
    await page.waitForFunction(()=>!!window.__derby);
    await page.evaluate(()=>window.__derby.renderEnabled=false);
    await page.evaluate(()=>window.__derby.start(true));
    await page.locator('#race-controls').waitFor({state:'visible'});
    await page.waitForFunction(()=>window.__derby.racers[0].elapsed>0.05,{},{timeout:60000});
    console.log(name, 'racing');
    const zone=await page.locator('.swipe-left').boundingBox();
    assert.ok(zone.x<60 && zone.width<160);
    await page.evaluate(()=>window.__derby.renderEnabled=false);
    const fire=async(selector,type,id,y)=>page.locator(selector).dispatchEvent(type,{pointerId:id,pointerType:'touch',clientX:selector.includes('left')?70:774,clientY:y,bubbles:true});
    await fire('.swipe-left','pointerdown',1,160);
    await fire('.swipe-left','pointermove',1,240);
    await page.waitForFunction(()=>window.__derby.racers[0]._boostTime>9);
    await fire('.swipe-left','pointerup',1,240);
    await page.waitForTimeout(1000);
    const forward=await page.evaluate(()=>window.__derby.racers[0].speed);
    assert.ok(forward>2);
    await fire('.swipe-right','pointerdown',2,260);
    await fire('.swipe-right','pointermove',2,170);
    await page.waitForFunction(()=>window.__derby.racers[0]._driveDirection===-1);
    await fire('.swipe-right','pointerup',2,170);
    await page.waitForFunction(()=>window.__derby.racers[0].speed<0,{},{timeout:12000});
    await fire('.swipe-left','pointerdown',3,200);
    await fire('.swipe-right','pointerdown',4,200);
    await page.waitForFunction(()=>window.__derby.controls.input.brake);
    await page.waitForFunction(()=>window.__derby.racers[0].speed===0);
    assert.equal(await page.evaluate(()=>window.__derby.racers[0]._boostTime),0);
    await page.locator('#dashboard-light').click();
    await page.waitForFunction(()=>document.querySelector('#dashboard-light').getAttribute('aria-pressed')==='true');
    await page.evaluate(()=>{window.__derby.renderEnabled=true;window.__derby.racers[0].s=200;for(let i=1;i<6;i++)window.__derby.racers[i].s=100-i*8;});
    await page.waitForFunction(()=>document.querySelector('#race-rank').textContent==='1/6');
    await page.screenshot({path:`verification/thumb-drive/${name}-phone.png`});
    await page.evaluate(()=>window.__derby.renderEnabled=false);
    await fire('.swipe-left','pointerup',3,200);
    await page.waitForFunction(()=>!window.__derby.controls.input.brake);
    await fire('.swipe-right','pointerup',4,200);
    await page.locator('#pause').click();
    await page.locator('#race-controls').waitFor({state:'hidden'});
    assert.deepEqual(errors,[]);
    results.push({engine:name,forwardSpeedAfterOneSecond:forward,upwardReverse:true,dualThumbBrake:true,headlight:true,rank:true,errors});
  } finally { await browser.close(); }
}
await writeFile('verification/thumb-drive/results.json',JSON.stringify(results,null,2));
console.log(JSON.stringify(results,null,2));
clearTimeout(hardStop);
